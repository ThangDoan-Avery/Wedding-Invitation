"use strict";

const fs = require("node:fs");
const path = require("node:path");

const IMAGE_EXTENSIONS = new Set([
  ".jpg",
  ".jpeg",
  ".png",
  ".webp",
  ".avif",
  ".gif",
  ".svg",
  ".bmp",
]);

const GENERATED_HEADER = "/* Generated by scripts/generate-album.cjs. Do not edit manually. */";
const ALBUM_GLOBAL = "INVITATION_ALBUM_PHOTOS";
const IMAGE_ASSET_STRING_FIELDS = ["src", "srcset", "sizes", "thumbSrc", "fullSrc"];
const IMAGE_ASSET_DIMENSION_FIELDS = ["width", "height"];

function compareText(left, right) {
  if (left === right) return 0;
  return left < right ? -1 : 1;
}

function normalizeNumberToken(token) {
  const normalized = token.replace(/^0+(?=\d)/u, "");
  return normalized || "0";
}

function compareNumberTokens(left, right) {
  const normalizedLeft = normalizeNumberToken(left);
  const normalizedRight = normalizeNumberToken(right);

  if (normalizedLeft.length !== normalizedRight.length) {
    return normalizedLeft.length < normalizedRight.length ? -1 : 1;
  }

  return compareText(normalizedLeft, normalizedRight);
}

function tokenizeNatural(value) {
  return value.normalize("NFC").toLowerCase().match(/\d+|\D+/gu) || [];
}

function naturalCompareFilenames(left, right) {
  const leftTokens = tokenizeNatural(left);
  const rightTokens = tokenizeNatural(right);
  const length = Math.max(leftTokens.length, rightTokens.length);

  for (let index = 0; index < length; index += 1) {
    const leftToken = leftTokens[index];
    const rightToken = rightTokens[index];

    if (leftToken === undefined) return -1;
    if (rightToken === undefined) return 1;

    const leftIsNumber = /^\d+$/u.test(leftToken);
    const rightIsNumber = /^\d+$/u.test(rightToken);
    let comparison = 0;

    if (leftIsNumber && rightIsNumber) {
      comparison = compareNumberTokens(leftToken, rightToken);
    } else if (leftIsNumber !== rightIsNumber) {
      comparison = leftIsNumber ? -1 : 1;
    } else {
      comparison = compareText(leftToken, rightToken);
    }

    if (comparison !== 0) return comparison;
  }

  // Resolve case, normalization and leading-zero ties without relying on locale or filesystem order.
  const normalizedComparison = compareText(left.normalize("NFC"), right.normalize("NFC"));
  return normalizedComparison || compareText(left, right);
}

function isAlbumImageFilename(filename) {
  return /^list/iu.test(filename) && IMAGE_EXTENSIONS.has(path.extname(filename).toLowerCase());
}

function scanAlbumFiles(assetsDirectory) {
  return fs
    .readdirSync(assetsDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && isAlbumImageFilename(entry.name))
    .map((entry) => entry.name)
    .sort(naturalCompareFilenames);
}

function encodePathSegment(segment) {
  return encodeURIComponent(segment).replace(/[!'()*]/gu, (character) =>
    `%${character.charCodeAt(0).toString(16).toUpperCase()}`,
  );
}

function getImageAsset(imageAssets, filename) {
  if (imageAssets instanceof Map) return imageAssets.get(filename);
  if (!imageAssets || typeof imageAssets !== "object") return undefined;
  return Object.prototype.hasOwnProperty.call(imageAssets, filename)
    ? imageAssets[filename]
    : undefined;
}

function normalizeImageAsset(imageAsset) {
  if (!imageAsset || typeof imageAsset !== "object" || Array.isArray(imageAsset)) return {};

  const normalized = {};
  IMAGE_ASSET_STRING_FIELDS.forEach((field) => {
    const value = imageAsset[field];
    if (typeof value === "string" && value.trim()) normalized[field] = value.trim();
  });
  IMAGE_ASSET_DIMENSION_FIELDS.forEach((field) => {
    const value = imageAsset[field];
    if (Number.isSafeInteger(value) && value > 0) normalized[field] = value;
  });
  return normalized;
}

function createAlbumManifest(filenames, imageAssets = {}) {
  return filenames.map((filename, index) => {
    const legacyPhoto = {
      src: `/assets/${encodePathSegment(filename)}`,
      alt: `Ảnh cưới Hữu Thắng và Thu Trang ${index + 1}`,
      position: "50% 50%",
    };
    const imageAsset = normalizeImageAsset(getImageAsset(imageAssets, filename));
    return Object.keys(imageAsset).length ? { ...legacyPhoto, ...imageAsset } : legacyPhoto;
  });
}

function escapeJsonForJavaScript(value) {
  return JSON.stringify(value, null, 2)
    .replace(/&/gu, "\\u0026")
    .replace(/</gu, "\\u003C")
    .replace(/>/gu, "\\u003E")
    .replace(/\u2028/gu, "\\u2028")
    .replace(/\u2029/gu, "\\u2029");
}

function serializeAlbumData(manifest) {
  return `${GENERATED_HEADER}\n\nglobalThis.${ALBUM_GLOBAL} = ${escapeJsonForJavaScript(manifest)};\n`;
}

function writeFileIfChanged(outputFile, content) {
  let existing = null;

  try {
    existing = fs.readFileSync(outputFile, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  if (existing === content) return false;

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, content, "utf8");
  return true;
}

function generateAlbumData({ assetsDirectory, outputFile, imageAssets = {} } = {}) {
  const projectRoot = path.resolve(__dirname, "..");
  const resolvedAssetsDirectory = assetsDirectory || path.join(projectRoot, "deploy", "assets");
  const resolvedOutputFile = outputFile || path.join(projectRoot, "deploy", "album-data.js");
  const filenames = scanAlbumFiles(resolvedAssetsDirectory);
  const manifest = createAlbumManifest(filenames, imageAssets);
  const content = serializeAlbumData(manifest);
  const changed = writeFileIfChanged(resolvedOutputFile, content);

  return {
    assetsDirectory: resolvedAssetsDirectory,
    outputFile: resolvedOutputFile,
    filenames,
    manifest,
    content,
    changed,
  };
}

if (require.main === module) {
  const result = generateAlbumData();
  const verb = result.changed ? "Generated" : "Verified";
  console.log(`${verb} ${path.relative(process.cwd(), result.outputFile)} with ${result.manifest.length} photo(s).`);
}

module.exports = {
  ALBUM_GLOBAL,
  IMAGE_EXTENSIONS,
  createAlbumManifest,
  encodePathSegment,
  escapeJsonForJavaScript,
  generateAlbumData,
  isAlbumImageFilename,
  naturalCompareFilenames,
  scanAlbumFiles,
  serializeAlbumData,
  writeFileIfChanged,
};
